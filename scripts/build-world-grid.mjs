#!/usr/bin/env node
/**
 * Rasterizes Natural Earth land polygons into a lon/lat cell grid used by the threat map
 * (src/content/impact/worldGrid.ts). The output is a bitmask (1 = land) packed as base64.
 *
 * The packages below are NOT project dependencies; install them ad hoc in a temporary folder:
 *   mkdir /tmp/geo && cd /tmp/geo && npm i world-atlas@2 topojson-client@3 d3-geo@3
 *   NODE_PATH=/tmp/geo/node_modules node scripts/build-world-grid.mjs > src/content/impact/worldGrid.ts
 *
 * Data: world-atlas (Natural Earth 1:50m "land" layer, public domain).
 */
import { createRequire } from 'node:module';
import { readFileSync } from 'node:fs';

const require = createRequire(process.env.NODE_PATH ? `${process.env.NODE_PATH}/` : import.meta.url);
const topojson = require('topojson-client');
const { geoContains } = require('d3-geo');
const topo = JSON.parse(readFileSync(require.resolve('world-atlas/land-50m.json'), 'utf8'));
const land = topojson.feature(topo, topo.objects.land);

const COLS = 240;              // 1.5° per cell
const LAT_TOP = 84;            // Arctic coast; Antarctica is left out to keep the map compact
const LAT_BOTTOM = -57;
const cell = 360 / COLS;
const ROWS = Math.round((LAT_TOP - LAT_BOTTOM) / cell);

const bytes = new Uint8Array(Math.ceil((COLS * ROWS) / 8));
let count = 0;
for (let r = 0; r < ROWS; r++) {
  const lat = LAT_TOP - (r + 0.5) * cell;
  for (let c = 0; c < COLS; c++) {
    const lon = -180 + (c + 0.5) * cell;
    if (geoContains(land, [lon, lat])) {
      const i = r * COLS + c;
      bytes[i >> 3] |= 1 << (7 - (i & 7));
      count++;
    }
  }
}

const b64 = Buffer.from(bytes).toString('base64');
process.stdout.write(`/**
 * Land mask for the stylized world map: ${COLS}×${ROWS} cells of ${cell}° (equirectangular),
 * latitudes ${LAT_TOP}° to ${LAT_BOTTOM}°, longitudes -180° to 180°. 1 bit per cell, row-major, MSB first.
 * ${count} land cells. Generated by scripts/build-world-grid.mjs from Natural Earth 1:50m land polygons
 * (world-atlas package, public domain). Do not edit by hand.
 */
export const WORLD_GRID = {
  cols: ${COLS},
  rows: ${ROWS},
  latTop: ${LAT_TOP},
  latBottom: ${LAT_BOTTOM},
  bits: '${b64}',
} as const;

/** Decodes the packed mask into a flat array (row-major) of 0/1 values. */
export function decodeWorldGrid(): Uint8Array {
  const binary = atob(WORLD_GRID.bits);
  const cells = new Uint8Array(WORLD_GRID.cols * WORLD_GRID.rows);
  for (let i = 0; i < cells.length; i++) {
    cells[i] = (binary.charCodeAt(i >> 3) >> (7 - (i & 7))) & 1;
  }
  return cells;
}
`);
